"""Generate the CJK-friendly classifier from Unicode 17.0.0 data files."""

import argparse
import hashlib
from pathlib import Path
import re


VERSION = "17.0.0"
SOURCES = {
    "EastAsianWidth.txt": "EastAsianWidth.txt",
    "Scripts.txt": "Scripts.txt",
    "emoji-data.txt": "emoji/emoji-data.txt",
    "StandardizedVariants.txt": "StandardizedVariants.txt",
}


def records(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if body:
            yield [field.strip() for field in body.split(";")]


def codepoints(value):
    parts = value.split("..")
    return range(int(parts[0], 16), int(parts[-1], 16) + 1)


def intervals(values):
    start = previous = None
    for value in sorted(values):
        if previous is not None and value != previous + 1:
            yield start, previous
            start = None
        if start is None:
            start = value
        previous = value
    if previous is not None:
        yield start, previous


def generate(directory):
    for filename in SOURCES:
        header = (directory / filename).read_text(encoding="utf-8")[:1000]
        if not re.search(r"17\.0(?:\.0)?\b", header):
            raise ValueError(f"{filename} must contain Unicode {VERSION} data")
    widths = {}
    for bounds, width in records(directory / "EastAsianWidth.txt"):
        widths.update(dict.fromkeys(codepoints(bounds), width))
    hangul = set()
    for bounds, script in records(directory / "Scripts.txt"):
        if script == "Hangul":
            hangul.update(codepoints(bounds))
    emoji = set()
    for bounds, property_name in records(directory / "emoji-data.txt"):
        if property_name == "Emoji_Presentation":
            emoji.update(codepoints(bounds))
    cjk = {cp for cp, width in widths.items() if width in {"W", "F", "H"}} - emoji
    cjk.update(hangul)
    ambiguous = []
    for sequence, description, *_ in records(directory / "StandardizedVariants.txt"):
        base, selector = (int(cp, 16) for cp in sequence.split())
        if (
            widths.get(base) == "A"
            and re.search(r"\bfullwidth form\b", description)
            and "non-fullwidth" not in description
        ):
            ambiguous.append((base, selector))

    lines = [
        "/* Generated by scripts/build_cjk_map.py; Unicode " + VERSION + ".",
        " * Data license: upstream_metadata/Unicode-LICENSE.txt.",
    ]
    for filename, source in SOURCES.items():
        digest = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
        lines.append(" * https://www.unicode.org/Public/" + VERSION + "/ucd/" + source)
        lines.append(" * SHA-256: " + digest)
    lines.extend([
        " */",
        "#define R(cp_min, cp_max) ((cp_min) | 0x40000000), ((cp_max) | 0x80000000)",
        "#define S(cp) (cp)",
        "static const unsigned MD_CJK_MAP[] = {",
    ])
    for start, end in intervals(cjk):
        value = f"S(0x{start:04x})" if start == end else f"R(0x{start:04x},0x{end:04x})"
        lines.append("    " + value + ",")
    lines.extend(["};", "#undef R", "#undef S", "static const unsigned MD_CJK_AMBIGUOUS_PUNCT[][2] = {"])
    for base, selector in sorted(ambiguous):
        lines.append(f"    {{ 0x{base:04x}, 0x{selector:04x} }},")
    lines.extend(["};", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd_directory", type=Path)
    parser.add_argument("--output", type=Path, default=Path("third_party/md4c/src/cjk.h"))
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd_directory), encoding="utf-8")
